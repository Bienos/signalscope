from dataclasses import dataclass, field
from datetime import datetime
from typing import Protocol
@dataclass
class ProviderVideo:
    id:str; url:str; creator_id:str; username:str; caption:str; published_at:datetime; language:str; market:str; metrics:dict[str,int|None]; hashtags:list[str]=field(default_factory=list); sound_id:str|None=None; sound_title:str|None=None; provider:str="unknown"; retrieved_at:datetime=field(default_factory=datetime.utcnow); freshness_at:datetime=field(default_factory=datetime.utcnow); confidence:float=.8; raw_reference:str=""; missing_fields:list[str]=field(default_factory=list)
class Provider(Protocol):
    def discover_videos(self)->list[ProviderVideo]: ...
    def get_video_metrics(self,video_ids:list[str])->dict[str,dict[str,int|None]]: ...
    def refresh_video_urls(self,video_urls:list[str])->list[ProviderVideo]: ...
    def get_creator_profile(self,creator_id:str)->dict: ...
    def get_creator_recent_videos(self,creator_id:str)->list[ProviderVideo]: ...
    def discover_hashtags(self)->list[dict]: ...
    def discover_sounds(self)->list[dict]: ...
    def get_sound_videos(self,sound_id:str)->list[ProviderVideo]: ...
    def health_check(self)->dict: ...
